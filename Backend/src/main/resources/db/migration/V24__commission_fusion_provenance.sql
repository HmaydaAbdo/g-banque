CREATE TABLE commission_fusion_source (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commission_fusion_id bigint NOT NULL REFERENCES commission(id) ON DELETE CASCADE,
    source_commission_id bigint NOT NULL,
    caution_id bigint NOT NULL,
    CONSTRAINT uk_commission_fusion_source_pair UNIQUE (commission_fusion_id, source_commission_id)
);

CREATE INDEX idx_commission_fusion_source_caution ON commission_fusion_source (caution_id);
CREATE INDEX idx_commission_fusion_source_fusion ON commission_fusion_source (commission_fusion_id);

ALTER TABLE commission ADD COLUMN fusion_provenance_incomplete boolean NOT NULL DEFAULT false;
ALTER TABLE commission_aud ADD COLUMN fusion_provenance_incomplete boolean;
UPDATE commission SET fusion_provenance_incomplete = true
WHERE operation = 'CAUTION' AND caution_id IS NULL;

CREATE TABLE commission_fusion_source_aud (
    id bigint NOT NULL,
    rev integer NOT NULL REFERENCES audit_revision_entity(id),
    revtype smallint,
    commission_fusion_id bigint,
    source_commission_id bigint,
    caution_id bigint,
    PRIMARY KEY (id, rev)
);
